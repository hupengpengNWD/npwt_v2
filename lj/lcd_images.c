/**
 * @brief 根据电量百分比获取电池图标指针
 */
const uint8_t* LCD_GetBatteryIcon(uint8_t battery_percent)
{
    if (battery_percent >= 90) {
        return BATTERY_ICON_4;  // 90-100% -> 4格
    } else if (battery_percent >= 70) {
        return BATTERY_ICON_3;  // 70-89% -> 3格
    } else if (battery_percent >= 40) {
        return BATTERY_ICON_2;  // 40-69% -> 2格
    } else if (battery_percent >= 15) {
        return BATTERY_ICON_1;  // 15-39% -> 1格
    } else {
        return BATTERY_ICON_0;  // 0-14% -> 0格
    }
}

