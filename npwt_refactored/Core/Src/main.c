#include "../Inc/system_config.h"
#include "../../HAL/Inc/hal_gpio.h"
#include "../../HAL/Inc/hal_timer.h"

/****************************************************************************
 * 全局变量
 ****************************************************************************/
extern volatile unsigned char FLG_SYS_10MS;  // 20ms系统滴答标志

/****************************************************************************
 * 主函数
 ****************************************************************************/
void main(void)
{
	/* ========== 系统初始化 ========== */
	
	/* 1. 清除看门狗 */
	asm("clrwdt");
	
	/* 2. 初始化GPIO */
	HAL_GPIO_Init();
	
	/* 3. 初始化Timer1 */
	HAL_Timer1_Init();
	
	/* 4. 初始化Timer2 */
	HAL_Timer2_Init();
	
	/* 5. 使能全局中断 */
	GIE = 1;
	PEIE = 1;
	asm("clrwdt");
	
	/* ========== 主循环 ========== */
	while (1)
	{
		/* 喂狗 */
		asm("clrwdt");
		
		/* 测试：翻转LED指示定时器工作 */
		/* 可以在这里添加测试代码 */
	}
}

/****************************************************************************
 * 中断服务程序
 ****************************************************************************/
void __interrupt() ISR(void)
{
	/* Timer1中断处理 */
	HAL_Timer1_ISR();
	
	/* Timer2中断处理 */
	HAL_Timer2_ISR();
}
