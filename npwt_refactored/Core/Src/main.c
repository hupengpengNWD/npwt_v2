/****************************************************************************
 * 文件名: main.c
 * 功能: 主程序入口（简化版本 - 单独测试定时器）
 * 
 * 说明: 
 *   测试Timer1和Timer2的初始化和中断
 * 
 * 创建日期: 2025-10-22
 ****************************************************************************/

#include "../Inc/system_config.h"
#include "../../HAL/Inc/hal_gpio.h"
#include "../../HAL/Inc/hal_timer.h"

/****************************************************************************
 * 全局变量
 ****************************************************************************/
extern volatile unsigned char FLG_SYS_10MS;  // 20ms系统滴答标志

/****************************************************************************
 * 主函数
 ****************************************************************************/
void main(void)
{
	/* ========== 系统初始化 ========== */
	
	/* 1. 清除看门狗 */
	asm("clrwdt");
	
	/* 2. 初始化GPIO */
	HAL_GPIO_Init();
	
	/* 3. 初始化定时器 */
	HAL_Timer_Init();     // Timer0: 10ms
	HAL_Timer1_Init();    // Timer1: 10ms
	HAL_PWM_Init();       // Timer3: 1ms
	
	/* 4. 使能全局中断 */
	T3CONbits.TMR3ON = 1; // 启动Timer3
	GIE = 1;
	PEIE = 1;
	asm("clrwdt");
	
	/* ========== 主循环 ========== */
	while (1)
	{
		/* 喂狗 */
		asm("clrwdt");
		
		/* 测试：10ms任务 */
		if (FLG_SYS_10MS)
		{
			FLG_SYS_10MS = 0;
			
			/* 翻转绿色LED指示10ms周期正常 */
			LATCbits.LATC4 ^= 1;
		}
	}
}

/****************************************************************************
 * 中断服务程序
 ****************************************************************************/
void __interrupt() ISR(void)
{
	/* Timer3中断处理（1ms） */
	HAL_Timer3_ISR();
	
	/* Timer0中断处理（10ms） */
	HAL_Timer_ISR();
	
	/* Timer1中断处理（10ms） */
	HAL_Timer1_ISR();
}
